import numpy as np


def sigmoid(z):
    return 1 / (1 + np.exp(-z))


def predict(x_scaled, w, b):
    z = np.dot(x_scaled, w) + b
    f = sigmoid(z)
    return f


def gradient(x_scaled, y, w, b):
    f = predict(x_scaled, w, b)
    error = f - y

    m = x_scaled.shape[0]

    dj_dw = np.dot(error, x_scaled) / m
    dj_db = error.sum() / m

    return dj_dw, dj_db


def gradient_descent(x_scaled, y, w, b, alpha, iterations):

    for i in range(iterations):

        dj_dw, dj_db = gradient(x_scaled, y, w, b)

        w = w - alpha * dj_dw
        b = b - alpha * dj_db

    return w, b


def feature_scaling(x):

    mu = np.mean(x, axis=0)
    sigma = np.std(x, axis=0)

    centered = x - mu
    scaled = centered / sigma

    return scaled, mu, sigma


